ok( 'App password has no spaces',        strpos( $decoded['mcpServers']['wordpress']['env']['WP_APP_PASSWORD'], ' ' ) === false );

// ── 8. Zip contains required files ────────────────────────────────────────────
echo "\n=== Plugin Zip Contents ===\n";
$zip_out = shell_exec( 'unzip -l ihf-migration-setup.zip 2>&1' );
ok( 'Zip contains main PHP file',   strpos( $zip_out, 'ihf-migration-setup.php' ) !== false );
ok( 'Zip contains CLAUDE.md',       strpos( $zip_out, 'CLAUDE.md' ) !== false );
ok( 'Zip contains admin.js',        strpos( $zip_out, 'admin.js' ) !== false );
ok( 'Zip contains admin.css',       strpos( $zip_out, 'admin.css' ) !== false );

// ── Summary ────────────────────────────────────────────────────────────────────
echo "\n";
$total = $pass + $fail;
echo "=== Results: {$pass}/{$total} passed" . ( $fail ? " — {$fail} FAILED" : ' — all good' ) . " ===\n\n";
exit( $fail > 0 ? 1 : 0 );
