$stripped = str_replace( ' ', '', $wp_formatted );
ok( 'Spaces stripped from WP app password', $stripped === 'AbCdEfGhIjKlMnOpQrStUvWx' );
ok( 'Result is alphanumeric only',           ctype_alnum( $stripped ) );

// ── 7. Config JSON structure ───────────────────────────────────────────────────
echo "\n=== Config JSON ===\n";
